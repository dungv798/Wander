// Kiểm tra nút "Xếp N nơi" có nhận chạm không khi bị nút nổi che một phần; chụp kết quả.
import path from 'node:path';
import { chromium } from 'playwright-core';
const BASE = 'http://localhost:8787';
const OUT = path.resolve('.tmp/walk');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, locale: 'vi-VN' });
const page = await ctx.newPage();
await page.goto(`${BASE}/`);
await page.evaluate(() => { localStorage.setItem('wander.web.onboarding.v1', '{"done":true}'); localStorage.setItem('wander.web.destination.v1', 'ha-noi'); });
await page.goto(`${BASE}/#/deck/ha-noi`); await page.reload();
for (let i = 0; i < 4; i += 1) { await page.getByRole('button', { name: 'Chọn nơi này', exact: true }).first().click(); await page.waitForTimeout(300); }
await page.goto(`${BASE}/#/picked`);
await page.getByRole('button', { name: /Lưu \d+ địa điểm thành chuyến/ }).click();
await page.getByRole('button', { name: 'Xác nhận', exact: true }).click();
await page.getByRole('button', { name: /Để sau/ }).click();
await page.waitForURL(/\/trip\//);
await page.waitForTimeout(2500);
const arrange = page.getByRole('button', { name: /^Xếp \d+ nơi/ });
const box = await arrange.boundingBox();
const fab = await page.getByRole('button', { name: /Thêm địa điểm/ }).boundingBox();
console.log('Xếp:', JSON.stringify(box), ' Thêm:', JSON.stringify(fab));
const hit = await page.evaluate(([x, y]) => { const e = document.elementFromPoint(x, y); return e ? (e.closest('button')?.textContent ?? e.tagName).trim().slice(0, 30) : null; }, [box.x + box.width / 2, box.y + box.height / 2]);
console.log('phần tử nhận chạm ở tâm nút Xếp:', hit);
await arrange.click();
await page.waitForTimeout(3000);
await page.screenshot({ path: path.join(OUT, 'xep-sau-khi-bam-giua.png') });
await page.getByRole('button', { name: /Áp dụng gợi ý/ }).click();
await page.waitForTimeout(1500);
await page.getByRole('tab', { name: 'Ngày 1', exact: true }).or(page.getByRole('button', { name: 'Ngày 1', exact: true })).first().click();
await page.waitForTimeout(1800);
const scrolled = await page.evaluate(() => [...document.querySelectorAll('*')].filter((e) => e.scrollTop > 0 && e.scrollHeight > e.clientHeight).map((e) => (e.className || e.tagName).toString().slice(0, 40) + ' scrollTop=' + Math.round(e.scrollTop)));
console.log('vùng đã cuộn sẵn khi vào Ngày 1:', JSON.stringify(scrolled));
const firstCard = await page.evaluate(() => { const c = [...document.querySelectorAll('article, li, .tcard, [class*=item]')].find((e) => e.textContent.includes('Hồ Hoàn Kiếm') && e.getBoundingClientRect().height > 60); return c ? JSON.stringify(c.getBoundingClientRect().toJSON()) : 'không thấy thẻ'; });
console.log('thẻ Hồ Hoàn Kiếm:', firstCard);
await page.screenshot({ path: path.join(OUT, 'ngay-1-da-xep.png') });
await page.evaluate(() => window.scrollBy(0, 500)); await page.waitForTimeout(500);
await page.screenshot({ path: path.join(OUT, 'ngay-1-da-xep-cuon.png') });
const overlap = await page.evaluate(() => { const fb = [...document.querySelectorAll('button')].filter((b) => { const r = b.getBoundingClientRect(); return r.width && r.top >= 0 && r.top < innerHeight; }); const out = []; for (let i = 0; i < fb.length; i += 1) for (let j = i + 1; j < fb.length; j += 1) { const a = fb[i].getBoundingClientRect(); const b = fb[j].getBoundingClientRect(); const ox = Math.min(a.right, b.right) - Math.max(a.left, b.left); const oy = Math.min(a.bottom, b.bottom) - Math.max(a.top, b.top); if (ox > 4 && oy > 4 && !fb[i].contains(fb[j]) && !fb[j].contains(fb[i])) out.push((fb[i].textContent.trim().slice(0, 18)) + ' x ' + (fb[j].textContent.trim().slice(0, 18)) + ' ' + Math.round(ox) + 'x' + Math.round(oy)); } return out; });
console.log('nút chồng nhau:', JSON.stringify(overlap));
console.log('url', page.url().split('#')[1]);
await browser.close();
