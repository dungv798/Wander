import { createContext, useContext } from 'react';
import { useNow } from '../../../shared/hooks/useNow.ts';
import { IDENTITY } from '../model/identity.const.ts';
import { isLocked, triesOf } from '../model/attemptLock.ts';
import type { LockScope, LockState } from '../model/attemptLock.ts';
import type { AnswerOutcome, ApprovalPreview, BegunReplacement, Evidence, RecoveryStarted, StepUpRequested } from '../api/IdentityGateway.ts';
import type { IdentitySnapshot, IdentityStatus, PairingRequest, PairingStatus, SessionState } from '../model/identity.types.ts';
import type { Flow } from '../model/identityFlow.types.ts';

/** A recovery attempt that has started on this device: the replacement code generated by the server and the session secret this device generated itself (not in effect yet). */
export interface RecoveryAttempt extends RecoveryStarted {
  readonly sessionToken: string;
}

/**
 * The identity actions; every action calls the real API and throws an `ApiError` with a code on failure (the caller reports the error to the user).
 * A successful action reloads the identity snapshot by itself so the UI always reflects the server.
 */
export interface IdentityActions {
  /** Makes sure this device has an identity (creates one if not); no recovery code yet. */
  readonly ensureIdentity: () => Promise<void>;
  /** Issues a replacement code generated by the server (phase 1); if there is a current code, evidence is needed. */
  readonly beginReplacement: (evidence?: Evidence) => Promise<BegunReplacement>;
  /** Confirms the replacement code (phase 2): the new code takes effect, the old code stops being valid. */
  readonly confirmReplacement: (pendingId: string, code: string) => Promise<void>;
  /** Asks for a re-authentication approval from another device. */
  readonly requestStepUp: () => Promise<StepUpRequested>;
  readonly revoke: (deviceId: string) => Promise<void>;
  /** The owner opened the Security screen: turns off the 'unseen' flag. */
  readonly markSeen: () => Promise<void>;
  /** Renames this device (the name was checked with `parseDeviceName`). */
  readonly renameHere: (name: string) => Promise<void>;
  /** Starts recovery with a code on this device (a device with no session yet); a wrong code throws `INVALID_CODE`. */
  readonly startRecovery: (code: string) => Promise<RecoveryAttempt>;
  /** Completes recovery: this device's session takes effect. */
  readonly completeRecovery: (attempt: RecoveryAttempt) => Promise<void>;
  /** This device asks to be paired (a new device); null if the request limit was exceeded. */
  readonly requestPairing: () => Promise<PairingRequest | null>;
  /** The pairing-request status of this device. */
  readonly pairingStatus: (request: PairingRequest, signal?: AbortSignal) => Promise<PairingStatus>;
  /** The pairing request was approved: this device becomes a trusted device. */
  readonly joinHere: (request: PairingRequest) => Promise<void>;
  /** The approving device types the code and previews the request (pairing or re-authentication). */
  readonly preview: (code: string) => Promise<ApprovalPreview>;
  /** Answers the request with the matching number; a wrong choice denies that request for good. */
  readonly answer: (preview: ApprovalPreview, number: number) => Promise<AnswerOutcome>;
  readonly deny: (preview: ApprovalPreview) => Promise<void>;
  /** Records one wrong entry at `scope` (5 of them lock temporarily); `clearFails` clears the count after a correct entry. */
  readonly fail: (scope: LockScope) => void;
  readonly clearFails: (scope: LockScope) => void;
  /** Turns off the 'just opened by recovery' reminder (the user has gone in to see the device list). */
  readonly ackRecovered: () => void;
  /** Forgets this device's old session (after the session-ended screen). */
  readonly loseSession: () => void;
  /** Reloads the identity snapshot from the server. */
  readonly refresh: () => Promise<void>;
}

/** The value of the identity context. */
export interface IdentityValue {
  readonly status: IdentityStatus;
  /** The identity of THIS DEVICE; null if there is no session, it is loading, the session ended or it could not be loaded. */
  readonly identity: IdentitySnapshot | null;
  readonly session: SessionState;
  readonly locks: LockState;
  readonly actions: IdentityActions;
  /** Opens an identity flow (an overlay sheet). */
  readonly startFlow: (flow: Flow) => void;
  readonly closeFlow: () => void;
  /** If there is an identity runs `then` at once; if not it opens the first-save explanation sheet (F2) and runs `then` when the user goes on (`then` may return a Promise). */
  readonly requireIdentity: (then: () => unknown) => void;
}

export const IdentityContext = createContext<IdentityValue | null>(null);

/** Access to the identity; throws if `IdentityProvider` was forgotten. */
export function useIdentity(): IdentityValue {
  const ctx = useContext(IdentityContext);
  if (!ctx) throw new Error('useIdentity phải nằm trong IdentityProvider');
  return ctx;
}

/** The 'needs an identity' gate: runs the action at once if there is already an identity, otherwise opens the first-save sheet and runs it when the user goes on (F2). */
export function useRequireIdentity(): (then: () => unknown) => void {
  return useIdentity().requireIdentity;
}

/** A persistent count of wrong entries for one place: `locked` (temporarily locked, opens by itself by the clock), `failed` (wrong at least once), `fail()`, `reset()`. */
export function useAttemptLock(scope: LockScope): { readonly locked: boolean; readonly failed: boolean; readonly fail: () => void; readonly reset: () => void } {
  const { locks, actions } = useIdentity();
  const now = useNow(IDENTITY.POLL_MS);
  return { locked: isLocked(locks, scope, now), failed: triesOf(locks, scope, now) > 0, fail: () => actions.fail(scope), reset: () => actions.clearFails(scope) };
}

/** This device once had a session but the server no longer accepts it (revoked from elsewhere): the session has ended. */
export function useSessionExpired(): boolean {
  return useIdentity().status === 'expired';
}
