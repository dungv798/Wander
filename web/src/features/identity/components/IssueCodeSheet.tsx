import { useEffect, useRef, useState } from 'react';
import { ApiError } from '../../../shared/api/ApiError.ts';
import { Sheet } from '../../../shared/ui/Sheet.tsx';
import { Button } from '../../../shared/ui/Button.tsx';
import { useToast } from '../../../shared/ui/Toast.tsx';
import { copyText } from '../../../shared/lib/clipboard.ts';
import { downloadCode, printCode } from '../hooks/codeExport.ts';
import { useReportError } from '../hooks/useReportError.ts';
import { IDENTITY_COPY as C } from '../model/identity.copy.ts';
import type { IssueSession, IssueSpec } from '../model/identityFlow.types.ts';
import { CheckStep, DoneStep, ShowStep } from './IssueSteps.tsx';

type Step = 'show' | 'check' | 'done';

/** Does nothing: Esc and tapping the background do NOT close the code-showing sheet (S10), only the Cancel/Done buttons close it. */
const LOCKED = (): void => undefined;
/** The backend error code when the new-code attempt has expired (15 minutes) or has been replaced by another attempt. */
const EXPIRED_ERRORS: readonly string[] = ['ATTEMPT_EXPIRED', 'NO_PENDING_REPLACEMENT'];

/** The waiting sheet while asking the server for a code: it cannot be closed with Esc or by tapping the background, only the Cancel button. */
function LoadingSheet({ onCancel }: { readonly onCancel: () => void }) {
  return (
    <Sheet label={C.code.titleNew} onClose={LOCKED}>
      <div className="pp">
        <div className="waitbox" role="status">
          <span className="spin" aria-hidden="true" />
          {C.code.loading}
        </div>
        <Button kind="ghost" block onClick={onCancel}>
          {C.code.cancel}
        </Button>
      </div>
    </Sheet>
  );
}

/**
 * The sheet that issues a new recovery code (S10): gets the code generated by the SERVER -> shows the code once -> type 2 of the 6 groups again -> the code takes effect at that moment
 * (QĐ-6) -> a last review. Cancelling midway changes nothing about the current code. Asking for the code runs exactly once even if React runs the effect twice.
 */
export function IssueCodeSheet({ issue, onClose }: { readonly issue: IssueSpec; readonly onClose: () => void }) {
  const toast = useToast();
  const report = useReportError();
  const [session, setSession] = useState<IssueSession | null>(null);
  const [step, setStep] = useState<Step>('show');
  const [indexes, setIndexes] = useState<readonly number[]>([]);
  const [busy, setBusy] = useState(false);
  const opened = useRef(false);

  useEffect(() => {
    if (opened.current) return; // StrictMode runs the effect twice: ask for the code only once
    opened.current = true;
    issue.open().then(setSession).catch((e: unknown) => {
      (issue.onOpenFailed ?? report)(e);
      onClose();
    });
  }, [issue, onClose, report]);

  if (!session) return <LoadingSheet onCancel={onClose} />;
  const code = session.code;

  /** Copies the code and reports the result; on failure it guides copying by hand. */
  const copy = (): void => void copyText(code.format()).then((ok) => toast.show(ok ? C.code.copied : C.code.copyFail));
  /** Confirmed correctly: if the attempt expired it starts over, otherwise it commits the code on the server and moves to the review step. */
  const confirm = (): void => {
    setBusy(true);
    session.commit().then(() => setStep('done')).catch((e: unknown) => {
      if (e instanceof ApiError && EXPIRED_ERRORS.includes(e.code)) {
        // the attempt expired or was replaced: there is nothing left to confirm, the user must start over
        (issue.onExpired ?? ((): void => report(e)))();
        onClose();
      } else report(e);
    }).finally(() => setBusy(false));
  };

  return (
    <Sheet label={C.code.titleNew} onClose={LOCKED}>
      {step === 'show' ? (
        <ShowStep
          code={code}
          purpose={issue.purpose}
          onCopy={copy}
          onNext={() => {
            setIndexes(code.pickChallenge());
            setStep('check');
          }}
          onSkip={issue.onSkip}
          onCancel={onClose}
        />
      ) : null}
      {step === 'check' ? <CheckStep code={code} indexes={indexes} busy={busy} onConfirm={confirm} onBack={() => setStep('show')} /> : null}
      {step === 'done' ? (
        <DoneStep
          code={code}
          onCopy={copy}
          onDownload={() => toast.show(downloadCode(code) ? C.code.downloaded : C.code.downloadFail)}
          onPrint={() => {
            if (!printCode(code)) toast.show(C.code.printFail);
          }}
          onFinish={issue.onDone}
        />
      ) : null}
    </Sheet>
  );
}
