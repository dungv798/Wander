param()
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$workspace = (Resolve-Path (Join-Path $PSScriptRoot '../..')).Path
$catalogPath = Join-Path $workspace 'backend/src/main/resources/catalog'
$outputPath = Join-Path $workspace 'web/public/assets/map-photos'
New-Item -ItemType Directory -Force -Path $outputPath | Out-Null
$files = [System.Collections.Generic.HashSet[string]]::new()
Get-ChildItem -LiteralPath $catalogPath -Filter '*.json' | ForEach-Object {
    $destination = Get-Content -LiteralPath $_.FullName -Raw -Encoding utf8 | ConvertFrom-Json
    foreach ($place in $destination.places) { foreach ($photo in $place.photos) { if ($photo.file) { [void]$files.Add($photo.file) } } }
    foreach ($moment in $destination.moments) { if ($moment.file) { [void]$files.Add($moment.file) } }
    if ($destination.coverPhoto.file) { [void]$files.Add($destination.coverPhoto.file) }
}
$totalOriginal = 0L
$totalThumb = 0L
$entries = [System.Collections.Generic.List[string]]::new()
foreach ($file in ($files | Sort-Object)) {
    if ($file -notmatch '^[a-zA-Z0-9_.-]+\.(jpg|jpeg|png)$') { throw "Invalid catalog filename: $file" }
    $source = Join-Path $catalogPath "photos/$file"
    # The recipe version must change if crop/size/encoding changes; content hash busts the immutable cache when the source changes.
    $sourceHash = (Get-FileHash -LiteralPath $source -Algorithm SHA256).Hash.Substring(0,12).ToLowerInvariant()
    $targetName = "$( [System.IO.Path]::GetFileNameWithoutExtension($file) )-96-v1-$sourceHash.jpg"
    $target = Join-Path $outputPath $targetName
    $totalOriginal += (Get-Item -LiteralPath $source).Length
    if (!(Test-Path -LiteralPath $target) -or (Get-Item -LiteralPath $source).LastWriteTimeUtc -gt (Get-Item -LiteralPath $target).LastWriteTimeUtc) {
        $image = [System.Drawing.Image]::FromFile($source)
        $bitmap = [System.Drawing.Bitmap]::new(96, 96)
        $graphics = [System.Drawing.Graphics]::FromImage($bitmap)
        try {
            $graphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
            $side = [Math]::Min($image.Width, $image.Height)
            $graphics.DrawImage($image, [System.Drawing.Rectangle]::new(0, 0, 96, 96), [single](($image.Width-$side)/2), [single](($image.Height-$side)/2), [single]$side, [single]$side, [System.Drawing.GraphicsUnit]::Pixel)
            $bitmap.Save($target, [System.Drawing.Imaging.ImageFormat]::Jpeg)
        } finally { $graphics.Dispose(); $bitmap.Dispose(); $image.Dispose() }
    }
    $totalThumb += (Get-Item -LiteralPath $target).Length
    $entries.Add("['$file', '$targetName']")
}
$names = $entries -join ', '
$manifest = "/** Generated by tools/catalog/build-map-thumbnails.ps1; content hash + versioned crop recipe for immutable cache. */`nexport const CATALOG_THUMBNAILS: ReadonlyMap<string, string> = new Map([$names]);`n"
[System.IO.File]::WriteAllText((Join-Path $workspace 'web/src/shared/map/catalogThumbnails.const.ts'), $manifest, [System.Text.UTF8Encoding]::new($false))
Write-Output "Map photos: $($files.Count); original bytes: $totalOriginal; thumbnail bytes: $totalThumb"
