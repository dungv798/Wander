package com.wander.identity.domain.constant;

import java.time.Duration;
import java.util.Set;

/**
 * Constants of the identity module (FEATURE tier): code and secret formats, time limits, actions that need re-authentication.
 * Error codes are in {@link IdentityErrorCodes}, messages in {@link IdentityMessages}.
 */
public final class IdentityConstants {

    /** Maximum number of days a session may go unused (sliding limit). */
    public static final int SESSION_IDLE_DAYS = 14;

    /** Maximum number of days a session may live since it was created. */
    public static final int SESSION_ABSOLUTE_DAYS = 90;

    /**
     * Minimum interval between two writes of {@code last_seen_at}: authenticating every request no longer causes a DB write (saves Neon
     * connections). Tiny compared with the sliding limit {@link #SESSION_IDLE_DAYS}, so the meaning of the sliding limit does not change.
     */
    public static final int SESSION_TOUCH_INTERVAL_MINUTES = 5;

    /** Crockford base32 alphabet (no I, L, O, U) so codes are less likely to be misread or miscopied by hand. */
    public static final String CODE_ALPHABET = "0123456789ABCDEFGHJKMNPQRSTVWXYZ";

    /** Mask that takes the low 5 bits of a byte to pick a symbol; 256 is divisible by 32 so the distribution is uniform. */
    public static final int SYMBOL_BIT_MASK = 31;

    /** Number of symbols of the recovery code: 30 x 5 bits = 150 bits; the code carries enough information to find the identity (MĐ-8). */
    public static final int RECOVERY_CODE_SYMBOLS = 30;

    /** Number of symbols of the short single-use code (device pairing, re-authentication approval). */
    public static final int SHORT_CODE_SYMBOLS = 8;

    /** Number of symbols per group when displaying the recovery code. */
    public static final int CODE_GROUP_SIZE = 5;

    /** Number of symbols in each half of the short code ({@code XXXX-XXXX}). */
    public static final int SHORT_CODE_HALF_LENGTH = 4;

    /** Character that separates the groups of a displayed code. */
    public static final char CODE_GROUP_SEPARATOR = '-';

    /** Number of random bytes of a new session secret (256 bits). */
    public static final int SESSION_TOKEN_BYTES = 32;

    /** Smallest and largest matching number (two digits, DR-018 E1). */
    public static final int MATCH_NUMBER_MIN = 10;
    public static final int MATCH_NUMBER_MAX = 99;

    /** Number of choices shown to the approving device: one real number and the decoys. */
    public static final int MATCH_OPTION_COUNT = 3;

    /** Separator of the choices when they are stored in one column. */
    public static final String MATCH_OPTIONS_SEPARATOR = ",";

    /** Maximum length of a device name (matches the CHECK in migration V5). */
    public static final int MAX_DEVICE_NAME_LENGTH = 60;

    /** Runs of whitespace (including the no-break space) in a device name, collapsed to a single space. */
    public static final String DEVICE_NAME_WHITESPACE_REGEX = "[\\p{Zs}\\s]+";

    /** The single space used when collapsing whitespace in a device name. */
    public static final String SINGLE_SPACE = " ";

    /** Maximum length of a code typed by the user, to reject oversized input before normalization. */
    public static final int MAX_CODE_INPUT_LENGTH = 80;

    /** Session secret generated by the party that keeps the session (at least 256 bits, base64url). */
    public static final String SESSION_TOKEN_REGEX = "^[A-Za-z0-9_-]{43,128}$";

    /** Id of a recovery attempt, generated by the client. */
    public static final String ATTEMPT_KEY_REGEX = "^[A-Za-z0-9_-]{16,128}$";

    /** Whitespace and hyphens, removed when normalizing a code typed by the user. */
    public static final String CODE_NOISE_REGEX = "[\\s-]";

    /** Hash algorithm. */
    public static final String HASH_ALGORITHM = "SHA-256";

    /** Prefix used when hashing a recovery code, so a code hash differs from a session-secret hash. */
    public static final String RECOVERY_HASH_PREFIX = "wander-recovery-v1:";

    /** Number of security events kept per identity and returned for 'Recent activity' (BE-11). */
    public static final int MAX_EVENTS_PER_IDENTITY = 50;

    /** Metric: security events appended to the activity log; tagged with the event kind. */
    public static final String METRIC_EVENTS_RECORDED = "wander.identity.events.recorded";

    /** Metric: deliveries of a security event that was already recorded (at-least-once delivery), ignored by the recorder. */
    public static final String METRIC_EVENTS_DUPLICATE = "wander.identity.events.duplicate";

    /** Tag name that holds the event kind. */
    public static final String METRIC_TAG_KIND = "kind";

    /** Configuration expression that supplies the recovery-code hashing key; there is NO default value (if missing, Spring does not start). */
    public static final String RECOVERY_PEPPER_EXPRESSION = "${wander.security.recovery-pepper}";

    /** Default version of the key used before key-rotation metadata existed. */
    public static final String RECOVERY_LEGACY_KEY_VERSION = "v1";

    /** Label of the current key, not a secret. */
    public static final String RECOVERY_KEY_VERSION_EXPRESSION = "${wander.security.recovery-key-version:v1}";

    /** Label of the old key, kept during the transition period. */
    public static final String RECOVERY_PREVIOUS_KEY_VERSION_EXPRESSION = "${wander.security.recovery-previous-key-version:}";

    /** The old key, configured only while codes or attempts still reference the old label. */
    public static final String RECOVERY_PREVIOUS_PEPPER_EXPRESSION = "${wander.security.recovery-previous-pepper:}";

    /** A key label that is safe to write as metadata and to check at startup. */
    public static final String RECOVERY_KEY_VERSION_REGEX = "^[A-Za-z0-9_-]{1,32}$";

    /** Length of the key-label metadata column. */
    public static final int RECOVERY_KEY_VERSION_MAX_LENGTH = 32;

    /** Maximum length of the key fingerprint stored in the DB (hex). */
    public static final int RECOVERY_KEY_FINGERPRINT_MAX_LENGTH = 64;

    /** Number of leading hex characters of the HMAC kept as a fingerprint: enough to tell keys apart but truncated so it cannot become an oracle. */
    public static final int RECOVERY_KEY_FINGERPRINT_HEX_LENGTH = 16;

    /** Prefix of the public constant that is hashed to get the key fingerprint; a different space than recovery codes. */
    public static final String RECOVERY_KEY_CHECK_PREFIX = "wander-key-check:";

    /** Prefix of an unresolved configuration placeholder; a key that starts with this prefix is treated as a missing key. */
    public static final String PLACEHOLDER_PREFIX = "${";

    /** HMAC algorithm used to hash recovery codes (DR-018 B3). */
    public static final String RECOVERY_HMAC_ALGORITHM = "HmacSHA256";

    /** Minimum length of the recovery-code hashing key (pepper), in bytes (256 bits). */
    public static final int RECOVERY_PEPPER_MIN_BYTES = 32;

    /** Time limit of a pending recovery attempt and of an unconfirmed replacement code (MĐ-6). The concrete value: waiting for the spec. */
    public static final Duration PENDING_TTL = Duration.ofMinutes(15);

    /** Time limit of a device pairing request and of a re-authentication approval request. */
    public static final Duration APPROVAL_TTL = Duration.ofMinutes(5);

    /** Action that needs re-authentication: regenerate the recovery code. */
    public static final String OPERATION_REGENERATE_CODE = "regenerate_code";

    /** The actions that may ask for a re-authentication approval. */
    public static final Set<String> STEP_UP_OPERATIONS = Set.of(OPERATION_REGENERATE_CODE);

    /** Reason a recovery code was invalidated: it was used to recover. */
    public static final String INVALIDATED_BY_RECOVERY = "recovered";

    /** Reason a recovery code was invalidated: it was replaced by another code. */
    public static final String INVALIDATED_BY_REPLACEMENT = "replaced";

    private IdentityConstants() {
    }
}
